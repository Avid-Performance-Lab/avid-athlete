const STORAGE_KEY = 'avid_lang'
let current = 'fr'

export function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'fr' || saved === 'en') return saved
  } catch (e) {}
  try {
    const nav = (navigator.language || 'fr').toLowerCase()
    return nav.startsWith('fr') ? 'fr' : 'en'
  } catch (e) { return 'fr' }
}

export function saveLang(l) {
  try { localStorage.setItem(STORAGE_KEY, l) } catch (e) {}
}

// Appelée par App() à chaque render, avant les enfants (même principe que C pour le thème)
export function setCurrentLang(l) { current = (l === 'en' ? 'en' : 'fr') }
export function getLang() { return current }

export function t(key) {
  const en = DICT[current] && DICT[current][key]
  if (en !== undefined) return en
  const fr = DICT.fr[key]
  return fr !== undefined ? fr : key
}

// Affichage seulement. Ne jamais utiliser le résultat comme valeur stockée ou comparée.
export function catLabel(cat) {
  const map = CAT_LABELS[current] || CAT_LABELS.fr
  return map[cat] !== undefined ? map[cat] : cat
}

export function dateLocale() { return current === 'en' ? 'en-GB' : 'fr-FR' }

// Texte avec variables : tf('confirm_del_block', { name }) remplace {name}
export function tf(key, vars) {
  let out = t(key)
  if (vars) Object.keys(vars).forEach(k => { out = out.split('{' + k + '}').join(String(vars[k])) })
  return out
}

// Sous-types cardio et types d'effort : AFFICHAGE seulement (valeurs stockées inchangées)
const CARDIO_SUB = { 'Course à pieds': 'Running', 'Rameur': 'Rowing', 'Vélo': 'Cycling', 'Ski-Erg': 'Ski-Erg' }
const EFFORT = { 'EF': 'EF', 'Tempo': 'Tempo', 'VMA': 'VMA', 'Fractionné': 'Intervals' }
export function cardioLabel(v) { return current === 'en' && CARDIO_SUB[v] ? CARDIO_SUB[v] : v }
export function effortLabel(v) { return current === 'en' && EFFORT[v] ? EFFORT[v] : v }

// Format des nombres (séparateur de milliers) selon la langue
export function numLocale() { return current === 'en' ? 'en-GB' : 'fr-FR' }

// Valeur de sexe stockée ('H', 'F', 'Homme', 'Femme', 'Autre') : AFFICHAGE seulement.
// En français on renvoie la valeur telle quelle ; inconnu → valeur brute.
const SEX_EN = { H: 'M', F: 'F', Homme: 'Male', Femme: 'Female', Autre: 'Other' }
export function sexLabel(v) { return current === 'en' && SEX_EN[v] ? SEX_EN[v] : v }

// Pastille de catégorie : en français on garde exactement la valeur stockée ;
// en anglais on traduit les catégories connues, sinon valeur brute. AFFICHAGE seulement.
const CAT_BADGE_EN = { JAMBES: 'LEGS', POUSSEE: 'PUSH', TIRAGE: 'PULL', 'FULL BODY': 'FULL BODY', CARDIO: 'CARDIO', AUTRES: 'OTHER' }
export function catBadge(cat) {
  if (current !== 'en' || !cat) return cat
  const k = String(cat).toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  return CAT_BADGE_EN[k] || cat
}

// Nom de bloc STOCKÉ affiché à l'utilisateur : « BLOCK 1 » (import Excel / dashboard) → « BLOC 1 ».
// AFFICHAGE seulement : la valeur enregistrée n'est jamais modifiée.
export function blocText(label) {
  if (typeof label !== 'string') return label
  return label.replace(/\bBLOCK\b/g, 'BLOC').replace(/\bBlock\b/g, 'Bloc').replace(/\bblock\b/g, 'bloc')
}
